// 证据装配:把一页的成员文件读成证据包(B 组)。
// 事实层全部由程序提取:内容哈希、结构清单、符号行号、引用边;阅读按角色分档(B2),
// 降档只在程序可验证时发生(B6),所有降级与读不到都写入预算账,不静默丢弃(D5)。
import { createHash } from 'node:crypto'
import { byCodeUnit } from '../modules/pathOrder.ts'
import type { DepEdge, FileStructure, SymbolRange } from '../shared/types.ts'
import type { FileFact } from '../depgraph/factCache.ts'
import type { WikiPlan, WikiPlanPage } from './wikiPlanTypes.ts'
import type {
  WikiEvidenceFile,
  WikiPageBudget,
  WikiPageEvidence,
  WikiSegment
} from './wikiReadTypes.ts'

export interface WikiEvidenceDeps {
  factOf: (relPath: string) => FileFact | null
  readFile: (relPath: string) => Promise<string | null>
}

const DATA_EXTS = new Set(['.json', '.jsonc', '.yaml', '.yml', '.toml', '.ini', '.env'])
const GENERATED_MARKER = /@generated|auto-generated|do not edit|generated by/i

function extOf(relPath: string): string {
  const dot = relPath.lastIndexOf('.')
  return dot < 0 ? '' : relPath.slice(dot).toLowerCase()
}

export function estTokens(text: string): number {
  return Math.ceil(Buffer.byteLength(text, 'utf8') / 3)
}

interface Block {
  kind: WikiSegment['kind']
  symbolName: string | null
  startLine: number
  endLine: number
}

/** 按符号边界切块:符号前的导入区、每个符号本体、符号之间的零散代码各成一块 */
function blocksOf(lines: string[], ranges: SymbolRange[]): Block[] {
  const blocks: Block[] = []
  const hasCode = (from: number, to: number): boolean =>
    lines.slice(from - 1, to).some((line) => line.trim() !== '')
  let cursor = 1
  for (const range of ranges) {
    if (range.startLine > cursor && hasCode(cursor, range.startLine - 1)) {
      blocks.push({
        kind: cursor === 1 ? 'header' : 'body',
        symbolName: null,
        startLine: cursor,
        endLine: range.startLine - 1
      })
    }
    blocks.push({
      kind: 'symbol',
      symbolName: range.name,
      startLine: range.startLine,
      endLine: range.endLine
    })
    cursor = range.endLine + 1
  }
  if (cursor <= lines.length && hasCode(cursor, lines.length)) {
    blocks.push({
      kind: cursor === 1 ? 'header' : 'body',
      symbolName: null,
      startLine: cursor,
      endLine: lines.length
    })
  }
  return blocks
}

/** 把块合并成段:单段不超字节上限;单个符号块本身超限时按行再切 */
function mergeBlocks(
  path: string,
  lines: string[],
  blocks: Block[],
  capBytes: number
): WikiSegment[] {
  const segments: WikiSegment[] = []
  let current: Block[] = []
  let currentBytes = 0
  const blockText = (block: Block): string =>
    lines.slice(block.startLine - 1, block.endLine).join('\n')
  const flush = (): void => {
    if (current.length === 0) return
    const text = current.map(blockText).join('\n')
    segments.push({
      id: `${path}#${segments.length}`,
      path,
      kind: current.length === 1 ? current[0]!.kind : 'body',
      symbolName: current.length === 1 ? current[0]!.symbolName : null,
      startLine: current[0]!.startLine,
      endLine: current[current.length - 1]!.endLine,
      text,
      estTokens: estTokens(text)
    })
    current = []
    currentBytes = 0
  }
  for (const block of blocks) {
    const bytes = Buffer.byteLength(blockText(block), 'utf8')
    if (bytes > capBytes) {
      flush()
      // 单块超限:按行窗口硬切,段名沿用符号名,靠行号区分
      let start = block.startLine
      while (start <= block.endLine) {
        let end = start
        let size = 0
        while (end <= block.endLine) {
          size += Buffer.byteLength(lines[end - 1] ?? '', 'utf8') + 1
          if (size > capBytes && end > start) break
          end++
        }
        const text = lines.slice(start - 1, end - 1).join('\n')
        segments.push({
          id: `${path}#${segments.length}`,
          path,
          kind: block.kind,
          symbolName: block.symbolName,
          startLine: start,
          endLine: end - 1,
          text,
          estTokens: estTokens(text)
        })
        start = end
      }
      continue
    }
    if (currentBytes + bytes > capBytes) flush()
    current.push(block)
    currentBytes += bytes
  }
  flush()
  return segments
}

/** 数据档的结构提取(B7):JSON 取顶层键,Markdown 取标题,其余取顶层键值行 */
function dataFactsOf(relPath: string, content: string): string[] {
  const ext = extOf(relPath)
  if (ext === '.json' || ext === '.jsonc') {
    try {
      const parsed: unknown = JSON.parse(content)
      if (parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)) {
        const keys = Object.keys(parsed)
        return [`顶层键 ${keys.length} 个:${keys.slice(0, 30).join(', ')}`]
      }
      if (Array.isArray(parsed)) return [`顶层为数组,共 ${parsed.length} 项`]
    } catch {
      return ['JSON 解析失败,仅登记文件存在']
    }
  }
  if (ext === '.md' || ext === '.mdx') {
    const headings = content
      .split('\n')
      .filter((line) => /^#{1,3}\s/.test(line))
      .map((line) => line.trim())
      .slice(0, 30)
    return headings.length > 0 ? headings : ['无标题结构']
  }
  const keys = content
    .split('\n')
    .map((line) => /^([A-Za-z0-9_.-]+)\s*[:=]/.exec(line)?.[1])
    .filter((key): key is string => key !== undefined)
    .slice(0, 30)
  return keys.length > 0 ? [`顶层键:${keys.join(', ')}`] : ['无可提取的键值结构']
}

/** 是否可验证地属于数据档(B6):数据扩展名且无符号结构,或带明确生成标记 */
function isProvableData(
  relPath: string,
  content: string,
  structure: FileStructure | null
): boolean {
  const head = content.split('\n').slice(0, 3).join('\n')
  if (GENERATED_MARKER.test(head)) return true
  if (!DATA_EXTS.has(extOf(relPath))) return false
  return structure === null || structure.symbolRanges.length === 0
}

export async function buildPageEvidence(
  input: {
    page: WikiPlanPage
    topicTitle: string | null
    plan: WikiPlan
    edges: DepEdge[]
    contextSize: number
  },
  deps: WikiEvidenceDeps
): Promise<WikiPageEvidence> {
  const { page, plan, edges, contextSize } = input
  const segmentTokenCap = Math.max(2000, Math.min(6000, Math.floor(contextSize * 0.72)))
  const capBytes = segmentTokenCap * 3
  const decisions: string[] = []
  const memberPaths = new Set(page.members.map((m) => m.path))
  const files: WikiEvidenceFile[] = []

  for (const member of [...page.members].sort((a, b) => byCodeUnit(a.path, b.path))) {
    const fact = deps.factOf(member.path)
    const structure = fact?.structure ?? null
    const base: WikiEvidenceFile = {
      path: member.path,
      role: member.role,
      tier: 'list',
      contentHash: null,
      sizeBytes: 0,
      languageId: structure?.languageId ?? '',
      structure,
      symbolRanges: structure?.symbolRanges ?? [],
      segments: [],
      dataFacts: null,
      evidenceNote: null
    }
    if (member.role === 'attached') {
      files.push(base)
      continue
    }
    const content = await deps.readFile(member.path)
    if (content === null) {
      base.evidenceNote = '文件读取失败或为二进制,未取得代码证据'
      decisions.push(`${member.path}:读取失败,证据缺失`)
      files.push(base)
      continue
    }
    base.contentHash = createHash('sha256').update(content, 'utf8').digest('hex')
    base.sizeBytes = Buffer.byteLength(content, 'utf8')
    if (isProvableData(member.path, content, structure)) {
      base.tier = 'data'
      base.dataFacts = dataFactsOf(member.path, content)
      files.push(base)
      continue
    }
    const lines = content.split('\n')
    let blocks = blocksOf(lines, base.symbolRanges)
    if (structure === null) {
      // B7 降级:分析器不支持的语言,按固定行窗纯文本切段
      base.evidenceNote = '分析器不支持该语言,按纯文本分段'
      decisions.push(`${member.path}:语言不支持,降为纯文本分段通读`)
      blocks = []
      for (let start = 1; start <= lines.length; start += 200) {
        blocks.push({
          kind: start === 1 ? 'header' : 'body',
          symbolName: null,
          startLine: start,
          endLine: Math.min(lines.length, start + 199)
        })
      }
    }
    if (member.role === 'supporting') {
      // 配角按符号切片:只留导入区与导出符号(及组件)本体
      const keep = new Set([...(structure?.exports ?? []), ...(structure?.reactComponents ?? [])])
      blocks = blocks.filter(
        (b) => b.kind === 'header' || (b.symbolName !== null && keep.has(b.symbolName))
      )
      base.tier = 'slice'
    } else {
      base.tier = 'full'
    }
    base.segments = mergeBlocks(member.path, lines, blocks, capBytes)
    files.push(base)
  }

  const internalEdges = edges
    .filter((e) => memberPaths.has(e.from) && memberPaths.has(e.to) && e.from !== e.to)
    .map((e) => ({ from: e.from, to: e.to }))
  const externalNames = [...new Set(files.flatMap((f) => f.structure?.imports ?? []))].sort(
    byCodeUnit
  )
  const segmentsTotal = files.reduce((sum, f) => sum + f.segments.length, 0)
  const budget: WikiPageBudget = {
    contextSize,
    segmentTokenCap,
    filesTotal: files.length,
    filesReadable: files.filter((f) => f.contentHash !== null).length,
    segmentsTotal,
    estNoteCalls: segmentsTotal,
    estInputTokens:
      files.reduce((sum, f) => sum + f.segments.reduce((s, seg) => s + seg.estTokens, 0), 0) +
      segmentsTotal * 400,
    decisions
  }
  void plan
  return {
    pageId: page.id,
    pageTitle: page.title,
    topicTitle: input.topicTitle,
    files,
    internalEdges,
    externalNames,
    budget
  }
}
